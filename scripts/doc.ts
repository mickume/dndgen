// Writes the declarations of every package to docs/generated/<package>.txt: the exported
// API at a glance, the TypeScript counterpart of `go doc -all`. Run through `make doc`.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const out = join(root, "docs/generated");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const packages = readdirSync(join(root, "packages")).filter((name) =>
  existsSync(join(root, "packages", name, "package.json")),
);
for (const name of packages) {
  const types = join(root, "packages", name, "build/types");
  const files = readdirSync(types, { recursive: true, encoding: "utf8" })
    .filter((file) => file.endsWith(".d.ts") && !file.startsWith("test"))
    .sort();
  const sections = files.map((file) => {
    const source = relative(
      root,
      join(root, "packages", name, "src", file.replace(/^src\//, "").replace(/\.d\.ts$/, ".ts")),
    );
    return `// ===== ${source}\n\n${readFileSync(join(types, file), "utf8").trim()}\n`;
  });
  const header = `// @dndgen/${name}: generated by \`make doc\` from the package's declarations. Do not edit.\n\n`;
  writeFileSync(join(out, `${name}.txt`), header + sections.join("\n"));
  console.log(`docs/generated/${name}.txt (${files.length} files)`);
}
